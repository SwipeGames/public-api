// Not every backend code is listed here: withdrawn codes (HRK/SLL/ANG), non-ISO
// aliases (RMB/PRB) and a few others are deliberately excluded from the public docs.
//
// `decimals` is the number of decimal places we actually honour, which for fiat is
// capped at 2 (KWD/BHD/OMR/IQD/TND/JOD/LYD are conventionally 3, but handled at 2).

export type CurrencyType = "main_fiat" | "sub_fiat" | "main_crypto" | "sub_crypto" | "virtual";

export interface Currency {
  code: string;
  name: string;
  type: CurrencyType;
  decimals: number;
  /** Base currency, for scaled units and sub-units only. */
  base?: string;
  /** Human conversion to the base unit, for scaled units and sub-units only. */
  conversion?: string;
  /** Another code denoting the exact same unit. Both are accepted and both are returned. */
  sameAs?: string;
}

